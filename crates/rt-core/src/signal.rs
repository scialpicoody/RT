//! Typed signals and slots (ADR 0003): an explicit [`Hub`] owns the objects,
//! connections and one delivery FIFO. Emissions queue by default and are
//! delivered at [`Hub::flush`]; direct calls are a per-connection opt-in.
//! Slots are method functions only — the public API admits plain `fn`
//! pointers; `#[slot]` generates arity-matching adapters (`name_slot`).

use core::any::{Any, TypeId};
use core::marker::PhantomData;
use std::rc::Rc;

use crate::audit::TraceEvent;
use crate::handle::{ConnectionId, Handle};
use crate::property::{CloneAny, PropertyInputs};
use crate::Object;

/// Compile-time-typed signal token: ties a signal to its owner type and
/// argument payload, so connect and emit cannot disagree at runtime.
/// Generated by `#[signal]`; zero string lookup on the emit path.
pub struct SignalId<Owner, Args> {
    index: u32,
    _phantom: PhantomData<fn(Owner, Args)>,
}

impl<Owner, Args> Clone for SignalId<Owner, Args> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<Owner, Args> Copy for SignalId<Owner, Args> {}

impl<Owner: 'static, Args: 'static> SignalId<Owner, Args> {
    pub const fn new(index: u32) -> Self {
        Self {
            index,
            _phantom: PhantomData,
        }
    }

    fn key(self) -> SignalKey {
        (TypeId::of::<Owner>(), self.index)
    }
}

/// Internal signal identity: owner type + signal index within its MetaObject.
type SignalKey = (TypeId, u32);

/// Type-erased slot invocation. The `Rc` carries only the plain fn pointer
/// the API admitted — no user state — and the single-threaded core (ADR 0003)
/// needs nothing stronger.
pub(crate) type ErasedCall = Rc<dyn Fn(&mut dyn Any, Box<dyn Any>)>;

/// Erases a typed method slot into the heterogeneous delivery call.
fn erase_call<Recv: 'static, Args: 'static>(slot: fn(&mut Recv, Args)) -> ErasedCall {
    Rc::new(move |recv, boxed| {
        let recv = recv
            .downcast_mut::<Recv>()
            .expect("rt: receiver type mismatch");
        let args = *boxed.downcast::<Args>().expect("rt: args type mismatch");
        slot(recv, args);
    })
}

struct Connection {
    key: SignalKey,
    emitter: Handle,
    receiver: Handle,
    call: ErasedCall,
    direct: bool,
}

struct Delivery {
    receiver: Handle,
    call: ErasedCall,
    args: Box<dyn Any>,
    signal_index: u32,
}

enum ObjState {
    Empty,
    Occupied {
        type_id: TypeId,
        props: PropsShim,
        value: Box<dyn Any>,
    },
}

/// Monomorphized accessor from the erased value to its property walker.
type PropsShim = fn(&mut dyn Any) -> Option<&mut dyn PropertyInputs>;

fn props_shim<T: PropertyInputs + 'static>(any: &mut dyn Any) -> Option<&mut dyn PropertyInputs> {
    any.downcast_mut::<T>().map(|t| t as &mut dyn PropertyInputs)
}

struct ObjSlot {
    generation: u32,
    state: ObjState,
}

enum ConnState {
    Empty,
    Occupied(Connection),
}

struct ConnSlot {
    generation: u32,
    state: ConnState,
}

/// Owns the objects, the typed connections, and the delivery FIFO.
///
/// Slots are `fn(&mut Recv, Args)`; `#[slot]` generates the adapters that
/// match a signal's payload arity (unit, single, or tuple).
pub struct Hub {
    objects: Vec<ObjSlot>,
    object_free: Vec<u32>,
    connections: Vec<ConnSlot>,
    connection_free: Vec<u32>,
    queue: Vec<Delivery>,
    trace: Option<Box<dyn Fn(TraceEvent)>>,
}

impl Default for Hub {
    fn default() -> Self {
        Self::new()
    }
}

impl Hub {
    pub fn new() -> Self {
        Self {
            objects: Vec::new(),
            object_free: Vec::new(),
            connections: Vec::new(),
            connection_free: Vec::new(),
            queue: Vec::new(),
            trace: None,
        }
    }

    /// Install the audit trace callback; see [`TraceEvent`]. Pass-through
    /// pluggable observation, no formatting or filtering inside core.
    pub fn set_trace(&mut self, f: impl Fn(TraceEvent) + 'static) {
        self.trace = Some(Box::new(f));
    }

    pub fn clear_trace(&mut self) {
        self.trace = None;
    }

    fn trace(&self, event: TraceEvent) {
        if let Some(f) = &self.trace {
            f(event);
        }
    }

    /// Store an object; returns its [`Handle`].
    pub fn insert<T: Object + 'static>(&mut self, value: T) -> Handle {
        let type_id = TypeId::of::<T>();
        let props: PropsShim = props_shim::<T>;
        let value: Box<dyn Any> = Box::new(value);
        match self.object_free.pop() {
            Some(index) => {
                let slot = &mut self.objects[index as usize];
                slot.state = ObjState::Occupied {
                    type_id,
                    props,
                    value,
                };
                Handle {
                    index,
                    generation: slot.generation,
                }
            }
            None => {
                let index = self.objects.len() as u32;
                self.objects.push(ObjSlot {
                    generation: 0,
                    state: ObjState::Occupied {
                        type_id,
                        props,
                        value,
                    },
                });
                Handle {
                    index,
                    generation: 0,
                }
            }
        }
    }

    pub fn get<T: 'static>(&self, handle: Handle) -> Option<&T> {
        self.any(handle)?.downcast_ref::<T>()
    }

    pub fn get_mut<T: 'static>(&mut self, handle: Handle) -> Option<&mut T> {
        self.any_mut(handle)?.downcast_mut::<T>()
    }

    /// The stored value behind a live handle; `None` for stale or empty slots.
    fn any(&self, handle: Handle) -> Option<&Box<dyn Any>> {
        let slot = self.objects.get(handle.index as usize)?;
        match (&slot.state, handle.generation == slot.generation) {
            (ObjState::Occupied { value, .. }, true) => Some(value),
            _ => None,
        }
    }

    fn any_mut(&mut self, handle: Handle) -> Option<&mut Box<dyn Any>> {
        let slot = self.objects.get_mut(handle.index as usize)?;
        match (&mut slot.state, handle.generation == slot.generation) {
            (ObjState::Occupied { value, .. }, true) => Some(value),
            _ => None,
        }
    }

    pub(crate) fn type_of(&self, handle: Handle) -> Option<TypeId> {
        let slot = self.objects.get(handle.index as usize)?;
        match (&slot.state, handle.generation == slot.generation) {
            (ObjState::Occupied { type_id, .. }, true) => Some(*type_id),
            _ => None,
        }
    }

    #[cfg(feature = "dynamic-invoke")]
    pub(crate) fn trace_event(&self, event: TraceEvent) {
        self.trace(event);
    }

    /// Destroy an object: bumps its generation, drops its value, and removes
    /// every connection it takes part in (as emitter or receiver). Queued
    /// deliveries targeting it are detected stale at flush.
    pub fn destroy(&mut self, handle: Handle) -> bool {
        let Some(slot) = self.objects.get_mut(handle.index as usize) else {
            return false;
        };
        if handle.generation != slot.generation || matches!(slot.state, ObjState::Empty) {
            return false;
        }
        slot.generation += 1;
        slot.state = ObjState::Empty;
        self.object_free.push(handle.index);

        let mut removed = 0;
        for (index, conn) in self.connections.iter_mut().enumerate() {
            if let ConnState::Occupied(c) = &conn.state
                && (c.emitter == handle || c.receiver == handle)
            {
                conn.generation += 1;
                conn.state = ConnState::Empty;
                self.connection_free.push(index as u32);
                removed += 1;
            }
        }
        self.trace(TraceEvent::Destroyed {
            object: handle,
            connections_removed: removed,
        });
        true
    }

    /// Connect a signal to a method slot; queued delivery at [`Hub::flush`].
    ///
    /// Panics when the emitter or receiver handle is stale or of the wrong
    /// type — connect-time signature errors surface immediately.
    pub fn connect<Owner, Recv, Args>(
        &mut self,
        emitter: Handle,
        signal: SignalId<Owner, Args>,
        receiver: Handle,
        slot: fn(&mut Recv, Args),
    ) -> ConnectionId
    where
        Owner: Object + 'static,
        Recv: 'static,
        Args: 'static,
    {
        self.store_connection(
            emitter,
            signal.key(),
            receiver,
            TypeId::of::<Recv>(),
            erase_call(slot),
            false,
        )
    }

    /// Connect with immediate delivery at [`Hub::emit`] instead of queueing.
    pub fn connect_direct<Owner, Recv, Args>(
        &mut self,
        emitter: Handle,
        signal: SignalId<Owner, Args>,
        receiver: Handle,
        slot: fn(&mut Recv, Args),
    ) -> ConnectionId
    where
        Owner: Object + 'static,
        Recv: 'static,
        Args: 'static,
    {
        self.store_connection(
            emitter,
            signal.key(),
            receiver,
            TypeId::of::<Recv>(),
            erase_call(slot),
            true,
        )
    }

    pub(crate) fn store_connection(
        &mut self,
        emitter: Handle,
        key: SignalKey,
        receiver: Handle,
        receiver_type: TypeId,
        call: ErasedCall,
        direct: bool,
    ) -> ConnectionId {
        match self.type_of(emitter) {
            Some(actual) if actual == key.0 => {}
            _ => panic!("rt: connect with stale or mistyped emitter handle"),
        }
        match self.type_of(receiver) {
            Some(actual) if actual == receiver_type => {}
            _ => panic!("rt: connect with stale or mistyped receiver handle"),
        }

        let conn = Connection {
            key,
            emitter,
            receiver,
            call,
            direct,
        };
        match self.connection_free.pop() {
            Some(index) => {
                let slot = &mut self.connections[index as usize];
                slot.state = ConnState::Occupied(conn);
                let id = ConnectionId {
                    index,
                    generation: slot.generation,
                };
                self.trace(TraceEvent::Connected {
                    emitter,
                    receiver,
                    signal_index: key.1,
                });
                id
            }
            None => {
                let index = self.connections.len() as u32;
                self.connections.push(ConnSlot {
                    generation: 0,
                    state: ConnState::Occupied(conn),
                });
                let id = ConnectionId {
                    index,
                    generation: 0,
                };
                self.trace(TraceEvent::Connected {
                    emitter,
                    receiver,
                    signal_index: key.1,
                });
                id
            }
        }
    }

    /// Remove one connection. Returns false when the id is already gone
    /// (disconnected, or destroyed with its endpoint).
    pub fn disconnect(&mut self, id: ConnectionId) -> bool {
        let Some(slot) = self.connections.get_mut(id.index as usize) else {
            return false;
        };
        if id.generation != slot.generation || matches!(slot.state, ConnState::Empty) {
            return false;
        }
        slot.generation += 1;
        slot.state = ConnState::Empty;
        self.connection_free.push(id.index);
        self.trace(TraceEvent::Disconnected { id });
        true
    }

    /// Emit a signal: queues one delivery per connection (cloning the payload
    /// for each) and returns the connection count reached. Direct connections
    /// fire immediately. Stale or mistyped emitters reach nothing and return 0.
    pub fn emit<Owner, Args>(
        &mut self,
        emitter: Handle,
        signal: SignalId<Owner, Args>,
        args: Args,
    ) -> usize
    where
        Owner: 'static,
        Args: Clone + 'static,
    {
        let key = signal.key();
        if self.type_of(emitter) != Some(key.0) {
            return 0;
        }
        let mut reached = 0;
        let mut pending_direct: Vec<(Handle, ErasedCall)> = Vec::new();
        for slot in &self.connections {
            if let ConnState::Occupied(conn) = &slot.state
                && conn.key == key
                && conn.emitter == emitter
            {
                reached += 1;
                if conn.direct {
                    pending_direct.push((conn.receiver, conn.call.clone()));
                } else {
                    self.queue.push(Delivery {
                        receiver: conn.receiver,
                        call: conn.call.clone(),
                        args: Box::new(args.clone()),
                        signal_index: key.1,
                    });
                }
            }
        }
        for (receiver, call) in pending_direct {
            if let Some(value) = self.any_mut(receiver) {
                call(&mut **value, Box::new(args.clone()));
                self.trace(TraceEvent::Delivered {
                    receiver,
                    signal_index: key.1,
                });
            } else {
                self.trace(TraceEvent::DroppedStale {
                    receiver,
                    signal_index: key.1,
                });
            }
        }
        self.trace(TraceEvent::Emitted {
            emitter,
            signal_index: key.1,
            reached,
        });
        reached
    }

    /// Deliver everything pending, deterministically: first dirty-property
    /// changes are evaluated and delivered (object insertion order, then
    /// declaration order, then connection order), then the queued emissions
    /// in FIFO order. Stale receivers are dropped. Returns deliveries made.
    pub fn flush(&mut self) -> usize {
        let mut changes: Vec<(Handle, SignalKey, Box<dyn CloneAny>)> = Vec::new();
        for (index, slot) in self.objects.iter_mut().enumerate() {
            if let ObjState::Occupied {
                type_id,
                props,
                value,
            } = &mut slot.state
            {
                let handle = Handle {
                    index: index as u32,
                    generation: slot.generation,
                };
                if let Some(inputs) = props(&mut **value) {
                    for (signal_index, payload) in inputs.take_dirty_changes() {
                        changes.push((handle, (*type_id, signal_index), payload));
                    }
                }
            }
        }

        let mut delivered = 0;
        for (emitter, key, payload) in changes {
            let mut to_deliver: Vec<(Handle, ErasedCall, Box<dyn Any>)> = Vec::new();
            for slot in &self.connections {
                let ConnState::Occupied(conn) = &slot.state else {
                    continue;
                };
                if conn.key == key && conn.emitter == emitter {
                    to_deliver.push((conn.receiver, conn.call.clone(), payload.clone_any()));
                }
            }
            for (receiver, call, args) in to_deliver {
                if let Some(value) = self.any_mut(receiver) {
                    call(&mut **value, args);
                    delivered += 1;
                    self.trace(TraceEvent::Delivered {
                        receiver,
                        signal_index: key.1,
                    });
                } else {
                    self.trace(TraceEvent::DroppedStale {
                        receiver,
                        signal_index: key.1,
                    });
                }
            }
        }

        for delivery in std::mem::take(&mut self.queue) {
            if let Some(value) = self.any_mut(delivery.receiver) {
                (delivery.call)(&mut **value, delivery.args);
                delivered += 1;
                self.trace(TraceEvent::Delivered {
                    receiver: delivery.receiver,
                    signal_index: delivery.signal_index,
                });
            } else {
                self.trace(TraceEvent::DroppedStale {
                    receiver: delivery.receiver,
                    signal_index: delivery.signal_index,
                });
            }
        }
        delivered
    }

    pub fn pending(&self) -> usize {
        self.queue.len()
    }

    /// By-name path (feature `dynamic-invoke`): emit with an erased payload
    /// against a pre-resolved key. Mirrors [`Hub::emit`] without generics.
    #[cfg(feature = "dynamic-invoke")]
    pub(crate) fn emit_erased(
        &mut self,
        emitter: Handle,
        key: SignalKey,
        payload: Box<dyn crate::property::CloneAny>,
    ) -> usize {
        if self.type_of(emitter) != Some(key.0) {
            return 0;
        }
        let mut reached = 0;
        let mut pending_direct: Vec<(Handle, ErasedCall, Box<dyn Any>)> = Vec::new();
        for slot in &self.connections {
            if let ConnState::Occupied(conn) = &slot.state
                && conn.key == key
                && conn.emitter == emitter
            {
                reached += 1;
                if conn.direct {
                    pending_direct.push((
                        conn.receiver,
                        conn.call.clone(),
                        payload.clone_any(),
                    ));
                } else {
                    self.queue.push(Delivery {
                        receiver: conn.receiver,
                        call: conn.call.clone(),
                        args: payload.clone_any(),
                        signal_index: key.1,
                    });
                }
            }
        }
        for (receiver, call, args) in pending_direct {
            if let Some(value) = self.any_mut(receiver) {
                call(&mut **value, args);
                self.trace(TraceEvent::Delivered {
                    receiver,
                    signal_index: key.1,
                });
            }
        }
        self.trace(TraceEvent::Emitted {
            emitter,
            signal_index: key.1,
            reached,
        });
        reached
    }
}
