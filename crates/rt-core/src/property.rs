//! Properties (ADR 0003): named State where only the latest value matters.
//! `Property::set` marks dirty — nothing fires synchronously; [`Hub`]'s flush
//! step evaluates changes in a deterministic order (object insertion order,
//! then declaration order) and notifies observers as queued signal deliveries.

use core::any::Any;
use core::cell::{Cell, RefCell};

/// A cloneable, type-erased property payload for heterogeneous fanout.
pub trait CloneAny: Any {
    /// A copy erased to `Any` — one delivery's worth.
    fn clone_any(&self) -> Box<dyn Any>;
    /// A copy that stays cloneable — for payloads that must fan out again
    /// later (relay chains).
    fn clone_any_boxed(&self) -> Box<dyn CloneAny>;
}

impl<T: Clone + 'static> CloneAny for T {
    fn clone_any(&self) -> Box<dyn Any> {
        Box::new(self.clone())
    }

    fn clone_any_boxed(&self) -> Box<dyn CloneAny> {
        Box::new(self.clone())
    }
}

/// Named state with change tracking. Values must be `Clone` (observers each
/// receive a copy). Interior mutability is `RefCell` — single-threaded core.
pub struct Property<T> {
    value: RefCell<T>,
    dirty: Cell<bool>,
}

impl<T> Property<T> {
    pub const fn new(value: T) -> Self {
        Self {
            value: RefCell::new(value),
            dirty: Cell::new(false),
        }
    }

    pub fn get(&self) -> T
    where
        T: Clone,
    {
        self.value.borrow().clone()
    }

    /// Store the latest value and mark dirty. Change notification happens at
    /// the next [`Hub`](crate::signal::Hub) flush — never synchronously.
    pub fn set(&self, value: T) {
        *self.value.borrow_mut() = value;
        self.dirty.set(true);
    }

    #[doc(hidden)]
    pub fn take_dirty(&self) -> bool {
        self.dirty.replace(false)
    }

    /// Non-destructive dirty probe: does not clear the mark. The binding
    /// engine uses it to decide re-evaluation without consuming the change.
    #[doc(hidden)]
    pub fn peek_dirty(&self) -> bool {
        self.dirty.get()
    }
}

/// Monomorphized accessor from an erased value to its property walker;
/// shared by typed insert and the derive-generated by-name factory.
pub type PropsShim = fn(&mut dyn Any) -> Option<&mut dyn PropertyInputs>;

/// Erased constructor for a registered kind: hands back a fresh, fully
/// initialized value plus the property hook the Hub insert path needs.
/// Plain fn pointers — static data, like the descriptors (ADR 0002).
#[derive(Debug, Clone)]
pub struct ObjectFactory {
    pub construct: fn() -> Box<dyn Any>,
    pub props: PropsShim,
}

/// Runtime hook the derive emits: reports each dirty property as
/// `(signal index, latest value)`, clearing the dirty marks, and serves the
/// erased by-name accessors behind the feature-gated dynamic path.
pub trait PropertyInputs {
    fn take_dirty_changes(&mut self) -> Vec<(u32, Box<dyn CloneAny>)>;

    /// The owned-children [`Handle`](crate::Handle)s of this object, in
    /// declaration order (ticket #31 lifecycle cascade). Default: none —
    /// only `#[object(children)]` fields override it.
    fn child_handles(&self) -> Vec<crate::Handle> {
        Vec::new()
    }

    /// Dirty probe by name: `Some` only when this type has the property;
    /// `None` means "no such property" (treated as not dirty by the binding
    /// engine — covers destroyed or stale dependencies).
    fn is_dirty(&self, name: &str) -> Option<bool> {
        let _ = name;
        None
    }

    /// Erased by-name read: `None` when this type has no such property.
    fn get_property(&self, name: &str) -> Option<Box<dyn Any>> {
        let _ = name;
        None
    }

    /// Erased by-name write: hands the value back when this type has no such
    /// property. A successful write marks the property dirty — notification
    /// happens at the next flush, like a typed `set`.
    fn set_property(&mut self, name: &str, value: Box<dyn Any>) -> Result<(), Box<dyn Any>> {
        let _ = name;
        Err(value)
    }
}
